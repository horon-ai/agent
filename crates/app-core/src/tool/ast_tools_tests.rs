// ToolOutput is not Debug, so `expect_err()` cannot be used on a tool result.
#![allow(clippy::err_expect)]

use super::{AstEditTool, AstGrepTool};
use crate::tool::{Tool, ToolContext, ToolExecutionMode};
use serde_json::{Value, json};
use std::path::Path;

fn context(dir: &Path, session: &str) -> ToolContext {
    ToolContext {
        session_id: session.to_string(),
        message_id: "message".to_string(),
        tool_call_id: "call".to_string(),
        working_dir: Some(dir.to_path_buf()),
        stdin_request_tx: None,
        graceful_shutdown_signal: None,
        execution_mode: ToolExecutionMode::Direct,
    }
}

fn seed(dir: &Path, name: &str, content: &str) -> std::path::PathBuf {
    let path = dir.join(name);
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).expect("mkdir");
    }
    std::fs::write(&path, content).expect("seed file");
    path
}

fn edit_input(paths: Vec<String>, expected: Option<usize>) -> Value {
    let mut value = json!({
        "ops": [{"pattern": "foo($A)", "rewrite": "bar($A)"}],
        "paths": paths
    });
    if let Some(expected) = expected {
        value["expected_replacements"] = json!(expected);
    }
    value
}

#[tokio::test]
async fn ast_grep_reports_paths_and_lines() {
    let dir = tempfile::tempdir().expect("temp dir");
    seed(dir.path(), "src/a.rs", "fn a() {\n    foo(1);\n}\n");
    seed(dir.path(), "src/b.rs", "fn b() {\n    foo(2);\n}\n");

    let output = AstGrepTool::new()
        .execute(json!({"pattern": "foo($A)"}), context(dir.path(), "ast-grep"))
        .await
        .expect("search");

    assert!(output.output.contains("src/a.rs:2-2: foo(1)"), "{}", output.output);
    assert!(output.output.contains("src/b.rs:2-2: foo(2)"), "{}", output.output);
}

#[tokio::test]
async fn ast_edit_previews_without_writing() {
    let dir = tempfile::tempdir().expect("temp dir");
    let file = seed(dir.path(), "a.rs", "fn a() {\n    foo(1);\n}\n");

    let output = AstEditTool::new()
        .execute(
            edit_input(vec!["a.rs".to_string()], None),
            context(dir.path(), "ast-preview"),
        )
        .await
        .expect("preview");

    assert!(
        output.output.contains("Preview only — no files changed."),
        "{}",
        output.output
    );
    assert!(output.output.contains("+    bar(1);"), "{}", output.output);
    assert_eq!(
        std::fs::read_to_string(&file).expect("unchanged"),
        "fn a() {\n    foo(1);\n}\n"
    );
}

#[tokio::test]
async fn ast_edit_applies_when_the_count_matches() {
    let dir = tempfile::tempdir().expect("temp dir");
    let file = seed(dir.path(), "a.rs", "fn a() {\n    foo(1);\n    foo(2);\n}\n");

    AstEditTool::new()
        .execute(
            edit_input(vec!["a.rs".to_string()], Some(2)),
            context(dir.path(), "ast-apply"),
        )
        .await
        .expect("apply");

    assert_eq!(
        std::fs::read_to_string(&file).expect("after apply"),
        "fn a() {\n    bar(1);\n    bar(2);\n}\n"
    );
}

#[tokio::test]
async fn ast_edit_refuses_a_count_mismatch_without_writing() {
    let dir = tempfile::tempdir().expect("temp dir");
    let file = seed(dir.path(), "a.rs", "fn a() {\n    foo(1);\n}\n");

    let error = AstEditTool::new()
        .execute(
            edit_input(vec!["a.rs".to_string()], Some(5)),
            context(dir.path(), "ast-mismatch"),
        )
        .await
        .err()
        .expect("mismatch must refuse")
        .to_string();

    assert_eq!(
        error,
        "Expected 5 replacements but the files now produce 1. Nothing written."
    );
    assert_eq!(
        std::fs::read_to_string(&file).expect("unchanged"),
        "fn a() {\n    foo(1);\n}\n"
    );
}

#[tokio::test]
async fn ast_edit_guards_generated_files() {
    let dir = tempfile::tempdir().expect("temp dir");
    let content = "// Code generated by protoc-gen-go. DO NOT EDIT.\nfn a() {\n    foo(1);\n}\n";
    let file = seed(dir.path(), "gen.rs", content);

    let error = AstEditTool::new()
        .execute(
            edit_input(vec!["gen.rs".to_string()], Some(1)),
            context(dir.path(), "ast-generated"),
        )
        .await
        .err()
        .expect("generated file must be refused")
        .to_string();

    assert!(error.contains("Cannot modify auto-generated file: gen.rs"), "{error}");
    assert_eq!(std::fs::read_to_string(&file).expect("unchanged"), content);
}

struct HomeGuard {
    previous: Option<std::ffi::OsString>,
}

impl HomeGuard {
    fn new(path: &Path) -> Self {
        let previous = std::env::var_os("HORON_AGENT_HOME");
        crate::env::set_var("HORON_AGENT_HOME", path);
        crate::config::Config::invalidate_cache();
        Self { previous }
    }
}

impl Drop for HomeGuard {
    fn drop(&mut self) {
        if let Some(previous) = self.previous.take() {
            crate::env::set_var("HORON_AGENT_HOME", previous);
        } else {
            crate::env::remove_var("HORON_AGENT_HOME");
        }
        crate::config::Config::invalidate_cache();
    }
}

struct MockProvider;

#[async_trait::async_trait]
impl crate::provider::Provider for MockProvider {
    async fn complete(
        &self,
        _messages: &[crate::message::Message],
        _tools: &[crate::message::ToolDefinition],
        _system: &str,
        _resume_session_id: Option<&str>,
    ) -> anyhow::Result<crate::provider::EventStream> {
        Err(anyhow::anyhow!("mock provider does not stream"))
    }

    fn name(&self) -> &str {
        "mock"
    }

    fn fork(&self) -> std::sync::Arc<dyn crate::provider::Provider> {
        std::sync::Arc::new(MockProvider)
    }
}

#[test]
fn ast_tools_stay_off_by_default_and_register_when_the_gate_is_on() {
    let _env = crate::storage::lock_test_env();
    let home = tempfile::tempdir().expect("home");
    let _guard = HomeGuard::new(home.path());

    let runtime = || {
        tokio::runtime::Builder::new_current_thread()
            .enable_all()
            .build()
            .expect("runtime")
    };

    runtime().block_on(async {
        let registry = crate::tool::Registry::new(
            std::sync::Arc::new(MockProvider) as std::sync::Arc<dyn crate::provider::Provider>
        )
        .await;
        let names = registry.tool_names().await;
        assert!(
            !names.iter().any(|name| name == "ast_grep" || name == "ast_edit"),
            "ast tools must stay unregistered by default, got {names:?}"
        );
        assert!(!crate::config::CORE_TOOLS.contains(&"ast_grep"));
        assert!(!crate::config::CORE_TOOLS.contains(&"ast_edit"));
    });

    let path = crate::config::Config::path().expect("config path");
    std::fs::create_dir_all(path.parent().expect("parent")).expect("create parent");
    std::fs::write(&path, "[tools]\nast_tools = true\n").expect("write config");
    crate::config::Config::invalidate_cache();

    runtime().block_on(async {
        let registry = crate::tool::Registry::new(
            std::sync::Arc::new(MockProvider) as std::sync::Arc<dyn crate::provider::Provider>
        )
        .await;
        let names = registry.tool_names().await;
        assert!(
            names.iter().any(|name| name == "ast_grep"),
            "[tools] ast_tools = true must register ast_grep, got {names:?}"
        );
        assert!(
            names.iter().any(|name| name == "ast_edit"),
            "[tools] ast_tools = true must register ast_edit, got {names:?}"
        );
    });
}
