use super::*;

fn write_temp(name: &str, body: &str) -> (tempfile::TempDir, std::path::PathBuf) {
    let temp = tempfile::tempdir().expect("tempdir");
    let path = temp.path().join(name);
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).expect("mkdir");
    }
    std::fs::write(&path, body).expect("write file");
    (temp, path)
}

#[test]
fn file_names_that_belong_to_a_generator_are_detected() {
    for name in [
        "zz_generated.deepcopy.go",
        "service.pb.go",
        "schema.pb.ts",
        "schema_pb2.py",
        "schema_pb2_grpc.py",
        "routes.gen.go",
        "api.swagger.json",
        "store.mocks.go",
        "store.mock.ts",
    ] {
        let (_temp, path) = write_temp(name, "nothing to see\n");
        assert!(detect(&path).is_some(), "{name} should be detected");
    }
}

#[test]
fn a_generated_marker_in_a_comment_is_detected() {
    let (_temp, path) = write_temp(
        "service.go",
        "package service\n\n// Code generated by protoc-gen-go. DO NOT EDIT.\n",
    );
    let marker = detect(&path).expect("protoc marker");
    assert!(marker.contains("Code generated by protoc-gen-go"), "{marker}");

    let (_temp, path) = write_temp("model.py", "# This file was automatically generated by x\n");
    assert!(detect(&path).is_some(), "python comment marker");

    let (_temp, path) = write_temp("schema.sql", "-- @generated\nCREATE TABLE t (id int);\n");
    assert!(detect(&path).is_some(), "sql comment marker");
}

#[test]
fn a_marker_outside_a_comment_does_not_count() {
    let (_temp, path) = write_temp(
        "notes.rs",
        "// ordinary comment\n\
         pub const TEXT: &str = \"Code generated by protoc-gen-go. DO NOT EDIT.\";\n",
    );
    assert_eq!(detect(&path), None);
}

#[test]
fn an_unknown_extension_is_checked_by_name_only() {
    let (_temp, path) = write_temp("notes.txt", "// Code generated by protoc-gen-go. DO NOT EDIT.\n");
    assert_eq!(detect(&path), None);
}

#[test]
fn an_ordinary_file_is_not_flagged() {
    let (_temp, path) = write_temp("lib.rs", "// A normal module.\npub fn f() {}\n");
    assert_eq!(detect(&path), None);
}

#[test]
fn the_refusal_explains_the_marker_and_the_switch() {
    let (_temp, path) = write_temp("g.go", "package g\n\n// Code generated by sqlc. DO NOT EDIT.\n");
    let text = refusal(&path, "g.go").expect("refusal");
    assert!(text.starts_with("Cannot modify auto-generated file: g.go\n"), "{text}");
    assert!(
        text.contains("This file appears to be automatically generated (detected marker: \""),
        "{text}"
    );
    assert!(
        text.contains("1. Find the source file or generator configuration"),
        "{text}"
    );
    assert!(
        text.contains("Set [tools] block_auto_generated = false to allow edits."),
        "{text}"
    );
}
