#[test]
fn test_parse_sha256sums_accepts_standard_and_binary_lines() {
    let digest_a = "a".repeat(64);
    let digest_b = "B".repeat(64);
    let digest_b_lower = "b".repeat(64);
    let contents = format!(
        "# generated by release workflow\n{}  horon-agent-linux-x86_64.tar.gz\r\n{} *horon-agent-windows-x86_64.exe\n",
        digest_a, digest_b
    );
    let parsed = parse_sha256sums(&contents).unwrap();
    assert_eq!(
        parsed.get("horon-agent-linux-x86_64.tar.gz").map(String::as_str),
        Some(digest_a.as_str())
    );
    assert_eq!(
        parsed.get("horon-agent-windows-x86_64.exe").map(String::as_str),
        Some(digest_b_lower.as_str())
    );
}

